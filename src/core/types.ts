/** One piece of the response body as the browser delivered it, with its arrival time. */
export type Chunk = {
  /** Milliseconds since the fetch() call started. */
  t: number;
  text: string;
};

export type EndStatus = "done" | "aborted" | "error";

/** Everything the page-side wrapper records about one streaming response. */
export type Capture = {
  id: string;
  url: string;
  contentType: string;
  /** HTTP status of the response. */
  status?: number;
  /** Response headers (lower-case names). Request headers are never recorded. */
  headers: Record<string, string>;
  /** Milliseconds from fetch() start until response headers arrived. */
  headersMs: number;
  chunks: Chunk[];
  end?: { t: number; status: EndStatus; message?: string };
  /** True when a size cap was hit; later chunks are not stored. */
  truncated?: boolean;
};

export type SseEvent = {
  /** Time of the chunk that completed this event. */
  t: number;
  event?: string;
  data: string;
  id?: string;
};

export type Provider =
  | "openai-chat"
  | "openai-responses"
  | "anthropic"
  | "gemini"
  | "ai-sdk-ui"
  | "unknown";

export type JsonCheck =
  | { ok: true; value: unknown }
  | { ok: false; error: string; position: number; line: number; col: number };

export type ToolCall = {
  id: string;
  name: string;
  /** Raw argument text, concatenated across chunks. */
  args: string;
  json: JsonCheck;
};

export type NormalizedFinish = "stop" | "length" | "tool_calls" | "error" | "other";

export type Usage = {
  raw: unknown;
  input?: number;
  output?: number;
  total?: number;
};

/**
 * A diagnostic generated by streamscope itself (not text from the provider).
 * `text` is the English sentence kept in `errors`/`warnings`; the panel translates by `code`.
 */
export type Notice = {
  level: "error" | "warning";
  code: "unknownFormat" | "streamFailed" | "aborted" | "truncated" | "unhandledEvent" | "extraChoices";
  /** Variable part: event type, or the network error message. */
  arg?: string;
  text: string;
};

export type Assembled = {
  provider: Provider;
  text: string;
  reasoning: string;
  tools: ToolCall[];
  finish: { raw: string; normalized: NormalizedFinish } | null;
  usage: Usage | null;
  errors: string[];
  warnings: string[];
  /** Diagnostics generated by streamscope, with codes for translation. Provider error text stays in `errors` only. */
  notices: Notice[];
  /** Number of SSE events parsed. */
  eventCount: number;
  /** Index of the first event that carried model output (text, reasoning or tool arguments). */
  firstOutputEvent: number | null;
};

export type Metrics = {
  headersMs: number;
  /** Time of the first output chunk, or null when the stream produced no output. */
  ttftMs: number | null;
  maxGapMs: number;
  /** Index of the chunk after which the longest gap happened (-1 when fewer than 2 chunks). */
  maxGapAfterChunk: number;
  stalls: number;
  totalMs: number;
  chunks: number;
  events: number;
  bytes: number;
};

export type ProviderResult = Omit<Assembled, "provider" | "eventCount">;

export type StreamscopeExportV1 = {
  schema: "streamscope/v1";
  exportedAt: string;
  url: string;
  contentType: string;
  status?: number;
  headers: Record<string, string>;
  headersMs: number;
  chunks: Chunk[];
  end?: { t: number; status: EndStatus; message?: string };
  truncated?: boolean;
  assembled: Assembled;
  metrics: Metrics;
};
